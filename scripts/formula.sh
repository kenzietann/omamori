#!/bin/sh
# Writes the Homebrew formula for a release, from the checksums that scripts/release.sh made.
# Usage: scripts/formula.sh v0.2.0 > omamori.rb   (run after scripts/release.sh v0.2.0)
set -eu

tag="${1:?usage: scripts/formula.sh v0.2.0}"
case "$tag" in
  v[0-9]*.[0-9]*.[0-9]*) ;;
  *) echo "the tag must look like v0.2.0" >&2; exit 1 ;;
esac
version="${tag#v}"
sums="${2:-dist/checksums.txt}"

# sum <os> <arch>: the sha256 of that archive. A missing or malformed entry stops the script.
sum() {
  name="omamori_${version}_$1_$2.tar.gz"
  value=$(awk -v f="$name" '$2 == f { print $1 }' "$sums")
  case "$value" in
    *[!0-9a-f]* | "") echo "no valid sha256 for $name in $sums" >&2; exit 1 ;;
  esac
  [ "${#value}" -eq 64 ] || { echo "the sha256 of $name is not 64 characters" >&2; exit 1; }
  printf '%s' "$value"
}

url() { printf 'https://github.com/kenzietann/omamori/releases/download/%s/omamori_%s_%s_%s.tar.gz' "$tag" "$version" "$1" "$2"; }

darwin_arm=$(sum darwin arm64)
darwin_amd=$(sum darwin amd64)
linux_arm=$(sum linux arm64)
linux_amd=$(sum linux amd64)

cat <<EOF
# Generated by scripts/formula.sh in kenzietann/omamori. Do not edit by hand.
class Omamori < Formula
  desc "Blue-team toolkit: log detection, forensic triage and AI analysis that code checks"
  homepage "https://github.com/kenzietann/omamori"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url darwin arm64)"
      sha256 "$darwin_arm"
    end
    on_intel do
      url "$(url darwin amd64)"
      sha256 "$darwin_amd"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux arm64)"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$(url linux amd64)"
      sha256 "$linux_amd"
    end
  end

  def install
    bin.install "omamori"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/omamori version")
  end
end
EOF
